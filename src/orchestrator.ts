/**
 * orchestrator.ts — Multi-agent parallel review orchestrator.
 *
 * Dispatches the PR diff to three specialised Gemini 2.5 Pro subagents
 * concurrently and merges their outputs into a single Markdown report
 * that is posted back to the pull request.
 */

import { GoogleGenAI } from "@google/genai";
import {
  getPullRequestDiff,
  postPRComment,
  type PullRequestRef,
} from "./github.js";

export type { PullRequestRef } from "./github.js";

// ─── Gemini client ──────────────────────────────────────────────────

const ai = new GoogleGenAI({ apiKey: process.env["GEMINI_API_KEY"]! });
const MODEL = "gemini-2.5-pro";

// ─── Agent definitions ─────────────────────────────────────────────

interface AgentSpec {
  name: string;
  emoji: string;
  systemPrompt: string;
}

const agents: AgentSpec[] = [
  {
    name: "Security Auditor",
    emoji: "🔒",
    systemPrompt: `You are an expert security auditor reviewing a GitHub pull-request diff.
Identify vulnerabilities: injection flaws, auth issues, secrets exposure, dependency risks,
weak cryptography, and missing input validation.
Output a Markdown table with columns: Severity | File | Line(s) | Finding | Recommendation.
If the diff is clean, state that explicitly. Review ONLY the changed lines.`,
  },
  {
    name: "Performance Analyst",
    emoji: "⚡",
    systemPrompt: `You are a senior performance engineer reviewing a GitHub pull-request diff.
Detect: algorithmic inefficiencies (O(n²)+), memory/resource leaks, blocking I/O,
N+1 queries, bundle bloat, and missing caching opportunities.
Output a Markdown table with columns: Impact | File | Line(s) | Finding | Suggestion.
If the diff is clean, state that explicitly. Review ONLY the changed lines.`,
  },
  {
    name: "Test Author",
    emoji: "🧪",
    systemPrompt: `You are a test engineer generating unit-test stubs for a GitHub pull-request diff.
For every new or modified exported function/class, produce vitest-compatible tests covering:
happy path, boundary values, null/undefined inputs, and error paths.
Use descriptive "it('should …')" naming. Mock external I/O. Output fenced TypeScript code blocks.
If a function is too complex, add a TODO comment instead of a misleading test.`,
  },
];

// ─── Core logic ─────────────────────────────────────────────────────

/**
 * Run a single subagent against the diff and return its Markdown output.
 */
async function runAgent(agent: AgentSpec, diff: string): Promise<string> {
  const response = await ai.models.generateContent({
    model: MODEL,
    contents: [
      {
        role: "user",
        parts: [
          {
            text: `Review the following pull-request diff:\n\n\`\`\`diff\n${diff}\n\`\`\``,
          },
        ],
      },
    ],
    config: {
      systemInstruction: agent.systemPrompt,
      temperature: 0.2, // deterministic reviews
      maxOutputTokens: 4096,
    },
  });

  return response.text ?? "_No output from agent._";
}

/**
 * Orchestrate a full review: fetch the diff, fan-out to all agents in
 * parallel, merge results, and post the compiled report back to the PR.
 */
export async function reviewPullRequest(pr: PullRequestRef): Promise<void> {
  console.log(
    `[orchestrator] Starting review for ${pr.owner}/${pr.repo}#${pr.pull_number}`,
  );

  // 1. Fetch the diff
  const diff = await getPullRequestDiff(pr);

  if (!diff || diff.trim().length === 0) {
    console.log("[orchestrator] Empty diff — skipping review.");
    return;
  }

  // 2. Fan-out to all agents concurrently
  const results = await Promise.all(
    agents.map(async (agent) => {
      console.log(`[orchestrator]  → Running ${agent.name}…`);
      try {
        const output = await runAgent(agent, diff);
        return `### ${agent.emoji} ${agent.name}\n\n${output}`;
      } catch (err) {
        const message = err instanceof Error ? err.message : String(err);
        console.error(`[orchestrator]  ✗ ${agent.name} failed: ${message}`);
        return `### ${agent.emoji} ${agent.name}\n\n> ⚠️ Agent failed: ${message}`;
      }
    }),
  );

  // 3. Compile the final report
  const report = [
    "## 🤖 PR Guardian — Automated Review",
    "",
    `> Reviewing **${pr.owner}/${pr.repo}#${pr.pull_number}** with Gemini 2.5 Pro`,
    "",
    "---",
    "",
    ...results,
    "",
    "---",
    `_Generated by PR Guardian at ${new Date().toISOString()}_`,
  ].join("\n");

  // 4. Post back to the PR
  await postPRComment(pr, report);
  console.log("[orchestrator] Review posted successfully.");
}
